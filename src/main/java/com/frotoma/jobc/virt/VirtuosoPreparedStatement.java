    @Override
    public ResultSet executeQuery() throws SQLException {        
        logger.debug("[Virtuoso] Sparql : " + this.queryBuilder.query());
        return stmt.executeQuery(this.queryBuilder.query());
    }

    @Override
    public int executeUpdate() throws SQLException {        
        logger.debug("[Virtuoso] Sparql : " + this.queryBuilder.query());
        switch (prepareMode) {
            case AUTO_GENERATED_KEYS:
                return stmt.executeUpdate(this.queryBuilder.query(), autoGeneratedKeys);
            case COLUMN_INDEXES:
                return stmt.executeUpdate(this.queryBuilder.query(), columnIndexes);
            case COLUMN_NAMES:
                return stmt.executeUpdate(this.queryBuilder.query(), columnNames);
            default:
                return stmt.executeUpdate(this.queryBuilder.query());
        }
    }

    @Override
    public boolean execute() throws SQLException {
        logger.debug("[Virtuoso] Sparql : " + this.queryBuilder.query());
        switch (prepareMode) {
            case AUTO_GENERATED_KEYS:
                return stmt.execute(this.queryBuilder.query(), autoGeneratedKeys);
            case COLUMN_INDEXES:
                return stmt.execute(this.queryBuilder.query(), columnIndexes);
            case COLUMN_NAMES:
                return stmt.execute(this.queryBuilder.query(), columnNames);
            default:
                return stmt.execute(this.queryBuilder.query());
        }
    }
    
