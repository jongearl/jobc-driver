    private String convert(String sql) {
        if (sql == null) return null;
        String trimmed = sql.trim();        
        if (!trimmed.toUpperCase().startsWith("SPARQL")) {
            trimmed = "SPARQL " + trimmed;
        }        
        logger.info("[Virtuoso] PreparedStatement : " + LogBuilder.generateOneline(trimmed));
        return trimmed;
    }

    private String replaceParams(String sql) {
        StringBuilder result = new StringBuilder();
        boolean inSingleQuote = false;
        boolean inDoubleQuote = false;

        for (int i = 0; i < sql.length(); i++) {
            char c = sql.charAt(i);

            if (c == '\'' && !inDoubleQuote) {
                inSingleQuote = !inSingleQuote;
                result.append(c);
            } else if (c == '"' && !inSingleQuote) {
                inDoubleQuote = !inDoubleQuote;
                result.append(c);
            } else if (c == '?' && !inSingleQuote && !inDoubleQuote) {
                boolean nextIsLetter = (i + 1 < sql.length())
                        && Character.isLetter(sql.charAt(i + 1));
                if (nextIsLetter) {
                    result.append(c);           // ?name 등 SPARQL 변수 → 그대로
                } else {
                    result.append("??");        // 단독 ? → MyBatis 파라미터 → ??
                }
            } else {
                result.append(c);
            }
        }
        return result.toString();
    }

