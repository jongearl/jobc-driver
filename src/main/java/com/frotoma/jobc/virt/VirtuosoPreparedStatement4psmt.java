    @Override
    public boolean execute() throws SQLException {
        String virtuosoSparql = this.builder.query();
        
        logger.debug("[Virtuoso] Sparql : " + virtuosoSparql);
        
        if( this.pstmt == null ){
            this.pstmt = conn.prepareStatement(virtuosoSparql);
        }
        
        setParameterValues();
        
        switch (prepareMode) {
            case AUTO_GENERATED_KEYS:
                return pstmt.execute(virtuosoSparql, autoGeneratedKeys);
            case COLUMN_INDEXES:
                
                int[] intColumnIndexs = new int[columnIndexes.length];
                for( Integer value : columnIndexes){
                    intColumnIndexs[value] = columnIndexes[value];
                }
                return pstmt.execute(virtuosoSparql, intColumnIndexs);
            case COLUMN_NAMES:
                return pstmt.execute(virtuosoSparql, columnNames);
            default:
                return pstmt.execute(virtuosoSparql);
        }        
    }
    
