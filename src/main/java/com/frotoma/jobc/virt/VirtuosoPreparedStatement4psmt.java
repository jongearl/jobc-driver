    private void setParameterValues() throws SQLException{
        Iterator<Integer> indexIt = parameterValues.keySet().iterator();
        
        while( indexIt.hasNext() ){
            Integer i = indexIt.next();
            Object param = parameterValues.get(i);
            
            logger.debug("[Virtuoso] Sparql Param : " + i +" = "+ param);
        
            if( param instanceof String ){
                logger.info("[Virtuoso] SPARQL PARAM : " + param );
                this.pstmt.setString(i, (String)param);                
            }else if(param instanceof URL){
                logger.info("[Virtuoso] SPARQL PARAM : " + param );
                this.pstmt.setURL(i, (URL)param);
            }else if(param instanceof Boolean){
                logger.info("[Virtuoso] SPARQL PARAM : " + param );
                this.pstmt.setBoolean(i, (Boolean)param);
            }else if(param instanceof Integer){
                logger.info("[Virtuoso] SPARQL PARAM : " + param );
                this.pstmt.setInt(i, (Integer)param);
            }else if(param instanceof Float){
                logger.info("[Virtuoso] SPARQL PARAM : " + param );
                this.pstmt.setFloat(i, (Float)param);
            }else if(param instanceof Double){
                logger.info("[Virtuoso] SPARQL PARAM : " + param );
                this.pstmt.setDouble(i, (Double)param);
            }else if(param instanceof IRIx){
                logger.info("[Virtuoso] SPARQL PARAM : " + param );                
                this.pstmt.setString(i, ((IRIx)param).toString());
            }else if(param instanceof Calendar){
                logger.info("[Virtuoso] SPARQL PARAM : " + param );
                this.pstmt.setObject(i, (Calendar)param);
            }else if(param instanceof Literal){
                logger.info("[Virtuoso] SPARQL PARAM : " + param );
                this.pstmt.setObject(i, (Literal)param);
            }else if(param instanceof Long){
                logger.info("[Virtuoso] SPARQL PARAM : " + param );
                this.pstmt.setObject(i, (Long)param);
            }else{
                logger.info("[Virtuoso] SPARQL PARAM : " + param );
                this.pstmt.setObject(i, param);            
            }            
        }        
    }

    @Override
    public ResultSet executeQuery() throws SQLException {        
        
        String virtuosoSparql = this.builder.query();
        
        logger.debug("[Virtuoso] Sparql : " + virtuosoSparql);
        
        if( this.pstmt == null ){
            this.pstmt = conn.prepareStatement(virtuosoSparql);
        }
        
        setParameterValues();
        
        return this.pstmt.executeQuery();
    }

